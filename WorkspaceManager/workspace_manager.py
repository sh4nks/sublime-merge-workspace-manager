#!/usr/bin/env python3
"""Workspace Manager for Sublime Merge.

Sublime Merge has no plugin API, so workspaces live in workspaces.json next to
this file and this script generates the command palette entries, menu and key
bindings that expose them inside Sublime Merge. Sublime Merge runs this script
through a git alias:

    git -c alias.wm=!python3 "<this file>" wm <subcommand> [arguments]

Run it directly for the command line interface:

    python3 workspace_manager.py --help
"""

import collections
import copy
import json
import os
import re
import shutil
import subprocess
import sys

PACKAGE_DIR = os.path.dirname(os.path.abspath(__file__))
PACKAGE_NAME = os.path.basename(PACKAGE_DIR)
PACKAGES_DIR = os.path.dirname(PACKAGE_DIR)
DATA_DIR = os.path.dirname(PACKAGES_DIR)
LOCAL_DIR = os.path.join(DATA_DIR, "Local")

WORKSPACES_FILE = os.path.join(PACKAGE_DIR, "workspaces.json")
COMMANDS_FILE = os.path.join(PACKAGE_DIR, "Workspaces.sublime-commands")
MENU_FILE = os.path.join(PACKAGE_DIR, "Main.sublime-menu")
KEYMAP_FILE = os.path.join(PACKAGE_DIR, "Default.sublime-keymap")
SESSION_FILES = ("Auto Save Session.sublime_session", "Session.sublime_session")

SCRIPT_IN_PACKAGES = "${packages}/%s/workspace_manager.py" % PACKAGE_NAME
HELPER_ARGV = ["-c", 'alias.wm=!python3 "%s"' % SCRIPT_IN_PACKAGES, "wm"]

EMPTY_WORKSPACES_FILE = """{
\t// Each workspace is a named list of repository paths. Tabs open in this
\t// order. "~" is expanded. Optional "keys" binds a shortcut that switches
\t// to the workspace. Run "Workspace Manager: Regenerate Commands" after
\t// editing this file by hand.
\t"workspaces": {
\t},
\t// Show a desktop notification after a workspace was changed.
\t"notifications": true
}
"""

GENERATED_HEADER = "Generated by workspace_manager.py from workspaces.json. Do not edit."


class UsageError(Exception):
    pass


JSON_STRING = r'"(?:\\.|[^"\\])*"'
COMMENTS = re.compile(r"(%s)|//[^\n]*|/\*.*?\*/" % JSON_STRING, re.DOTALL)
TRAILING_COMMAS = re.compile(r"(%s)|,(?=\s*[\]}])" % JSON_STRING)


def loads_lenient(text):
    """Parse JSON that may contain // and /* */ comments and trailing commas."""
    def keep_strings(match):
        return match.group(1) or ""
    return json.loads(TRAILING_COMMAS.sub(keep_strings, COMMENTS.sub(keep_strings, text)))


def load_json_file(path):
    with open(path, encoding="utf-8") as handle:
        return loads_lenient(handle.read())


def load_workspaces():
    if not os.path.exists(WORKSPACES_FILE):
        return {"workspaces": {}, "notifications": True}
    try:
        data = load_json_file(WORKSPACES_FILE)
    except ValueError as error:
        raise UsageError("workspaces.json is not valid JSON: %s" % error)
    if not isinstance(data, dict):
        raise UsageError("workspaces.json must contain a JSON object")
    workspaces = data.setdefault("workspaces", {})
    if not isinstance(workspaces, dict):
        raise UsageError('"workspaces" in workspaces.json must be an object')
    for name, workspace in list(workspaces.items()):
        if isinstance(workspace, list):
            workspace = {"repos": workspace}
            workspaces[name] = workspace
        if not isinstance(workspace, dict):
            raise UsageError("workspace %r must be an object or a list of paths" % name)
        repos = workspace.setdefault("repos", [])
        if not isinstance(repos, list) or not all(isinstance(r, str) for r in repos):
            raise UsageError('"repos" of workspace %r must be a list of paths' % name)
    return data


def save_workspaces(data):
    ordered = {
        "workspaces": {
            name: data["workspaces"][name]
            for name in sorted(data["workspaces"], key=str.lower)
        }
    }
    for key, value in data.items():
        if key != "workspaces":
            ordered[key] = value
    write_json(WORKSPACES_FILE, ordered)


def write_json(path, value):
    temp_path = path + ".tmp"
    with open(temp_path, "w", encoding="utf-8") as handle:
        json.dump(value, handle, indent="\t", ensure_ascii=False)
        handle.write("\n")
    os.replace(temp_path, path)


def normalize(path):
    return os.path.normcase(os.path.realpath(os.path.expanduser(path)))


def same_path(a, b):
    return normalize(a) == normalize(b)


def validate_name(name):
    name = name.strip()
    if not name:
        raise UsageError("workspace name must not be empty")
    if "$" in name:
        raise UsageError("workspace name must not contain '$'")
    return name


def find_workspace(data, name):
    """Return the stored name of the workspace called name, ignoring case."""
    return next((existing for existing in data["workspaces"] if existing.lower() == name.lower()), None)


def require_workspace(data, name):
    existing = find_workspace(data, name)
    if existing is None:
        raise UsageError("no workspace named %r (known: %s)" % (name, ", ".join(sorted(data["workspaces"])) or "none"))
    return existing


def current_repository(explicit=None):
    path = explicit or os.getcwd()
    path = os.path.abspath(os.path.expanduser(path))
    if not os.path.isdir(path):
        raise UsageError("%s is not a directory" % path)
    return path


def session_windows():
    """Yield the tab paths of each window from the newest saved session."""
    candidates = []
    for file_name in SESSION_FILES:
        path = os.path.join(LOCAL_DIR, file_name)
        if os.path.exists(path):
            candidates.append((os.path.getmtime(path), path))
    for _, path in sorted(candidates, reverse=True):
        try:
            with open(path, encoding="utf-8") as handle:
                session = json.load(handle)
        except (OSError, ValueError):
            continue
        for window in session.get("windows", []):
            tabs = [tab.get("path") for tab in window.get("tabs", [])]
            yield [tab for tab in tabs if tab]


def tabs_of_window_containing(repo):
    for tabs in session_windows():
        if any(same_path(tab, repo) for tab in tabs):
            return tabs
    return None


# --- generation --------------------------------------------------------------

def expand(path):
    return os.path.expanduser(path)


def open_commands(repos):
    return [["open_repository", {"path": expand(repo)}] for repo in repos]


def chain(commands):
    return {"command": "chain", "args": {"commands": commands}}


def switch_command(repos):
    return chain([["new_window"], ["close_window"]] + open_commands(repos))


def open_in_new_window_command(repos):
    return chain([["new_window"]] + open_commands(repos))


def open_here_command(repos):
    return chain(open_commands(repos))


def helper_command(*args):
    return {"command": "git", "args": {"argv": HELPER_ARGV + list(args)}}


def prompting(command):
    """Wrap a command that uses $text so menus collect the input first."""
    return {"command": "show_command_palette", "args": command}


def edit_file_command():
    return {
        "command": "open_in_editor",
        "args": {
            "path": "${packages}/%s/workspaces.json" % PACKAGE_NAME,
            "default": EMPTY_WORKSPACES_FILE,
        },
    }


def with_caption(caption, command):
    entry = {"caption": caption}
    entry.update(command)
    return entry


def sorted_workspaces(data):
    return sorted(data["workspaces"].items(), key=lambda item: item[0].lower())


def build_commands(data):
    entries = []
    for name, workspace in sorted_workspaces(data):
        repos = workspace["repos"]
        entries += [
            with_caption("Workspace: Switch to %s" % name, switch_command(repos)),
            with_caption("Workspace: Open %s in New Window" % name, open_in_new_window_command(repos)),
            with_caption("Workspace: Open %s Here" % name, open_here_command(repos)),
            with_caption("Workspace Manager: Add Current Repository to %s" % name, helper_command("add", name)),
            with_caption("Workspace Manager: Remove Current Repository from %s" % name, helper_command("remove", name)),
            with_caption("Workspace Manager: Rename %s…" % name, helper_command("rename", name, "$text")),
            with_caption("Workspace Manager: Delete %s" % name, helper_command("delete", name)),
        ]
    entries += [
        with_caption("Workspace Manager: Save Open Tabs as Workspace…", helper_command("save", "$text")),
        with_caption("Workspace Manager: New Workspace from Current Repository…", helper_command("new", "$text")),
        with_caption("Workspace Manager: Edit Workspaces File", edit_file_command()),
        with_caption("Workspace Manager: Regenerate Commands", helper_command("generate")),
    ]
    return entries


def build_menu(data):
    children = []
    for name, workspace in sorted_workspaces(data):
        repos = workspace["repos"]
        children.append({
            "caption": name,
            "children": [
                with_caption("Switch", switch_command(repos)),
                with_caption("Open in New Window", open_in_new_window_command(repos)),
                with_caption("Open Here", open_here_command(repos)),
                {"caption": "-"},
                with_caption("Add Current Repository", helper_command("add", name)),
                with_caption("Remove Current Repository", helper_command("remove", name)),
                with_caption("Rename…", prompting(helper_command("rename", name, "$text"))),
                with_caption("Delete", helper_command("delete", name)),
            ],
        })
    if children:
        children.append({"caption": "-"})
    children += [
        with_caption("Save Open Tabs as Workspace…", prompting(helper_command("save", "$text"))),
        with_caption("New Workspace from Current Repository…", prompting(helper_command("new", "$text"))),
        {"caption": "-"},
        with_caption("Edit Workspaces File", edit_file_command()),
        with_caption("Regenerate Commands", helper_command("generate")),
    ]
    return [{"id": "file", "children": [{"caption": "Workspaces", "id": "workspaces", "children": children}]}]


def build_keymap(data):
    bindings = []
    for name, workspace in sorted_workspaces(data):
        keys = workspace.get("keys")
        if not keys:
            continue
        if isinstance(keys, str):
            keys = [keys]
        bindings.append({"keys": keys, **switch_command(workspace["repos"])})
    return bindings


def generate(data):
    write_json(COMMANDS_FILE, build_commands(data))
    write_json(MENU_FILE, build_menu(data))
    write_json(KEYMAP_FILE, build_keymap(data))
    return "generated commands for %d workspace(s)" % len(data["workspaces"])


# --- feedback ----------------------------------------------------------------

def notify(data, message):
    if not data.get("notifications", True):
        return
    try:
        if sys.platform.startswith("linux") and shutil.which("notify-send"):
            subprocess.Popen(["notify-send", "-a", "Sublime Merge", "Workspace Manager", message])
        elif sys.platform == "darwin":
            script = 'display notification "%s" with title "Workspace Manager"' % message.replace('"', "'")
            subprocess.Popen(["osascript", "-e", script])
    except OSError:
        pass


# --- subcommands -------------------------------------------------------------

def cmd_generate(data, args):
    return generate(data)


def cmd_list(data, args):
    if not data["workspaces"]:
        return "no workspaces defined"
    lines = []
    for name, workspace in sorted_workspaces(data):
        lines.append(name)
        for repo in workspace["repos"]:
            lines.append("    " + repo)
    return "\n".join(lines)


def cmd_new(data, args):
    if not args:
        raise UsageError("usage: new <name> [repository path]")
    name = validate_name(args[0])
    repo = current_repository(args[1] if len(args) > 1 else None)
    if find_workspace(data, name) is not None:
        raise UsageError("workspace %r already exists; use 'add' to add repositories to it" % name)
    data["workspaces"][name] = {"repos": [repo]}
    return "created workspace %r with %s" % (name, repo)


def cmd_save(data, args):
    if not args:
        raise UsageError("usage: save <name> [repository path]")
    name = validate_name(args[0])
    repo = current_repository(args[1] if len(args) > 1 else None)
    tabs = tabs_of_window_containing(repo)
    note = ""
    if tabs is None:
        tabs = [repo]
        note = ("\nSublime Merge has not auto-saved its session since this repository was opened,"
                " so only the current repository was recorded; run the command again in a"
                " minute or use 'Add Current Repository'")
    existing = find_workspace(data, name) or name
    workspace = data["workspaces"].setdefault(existing, {})
    workspace["repos"] = tabs
    return "saved workspace %r with %d repositories%s" % (existing, len(tabs), note)


def cmd_add(data, args):
    if not args:
        raise UsageError("usage: add <name> [repository path]")
    name = require_workspace(data, validate_name(args[0]))
    repo = current_repository(args[1] if len(args) > 1 else None)
    repos = data["workspaces"][name]["repos"]
    if any(same_path(existing, repo) for existing in repos):
        return "%s is already part of workspace %r" % (repo, name)
    repos.append(repo)
    return "added %s to workspace %r" % (repo, name)


def cmd_remove(data, args):
    if not args:
        raise UsageError("usage: remove <name> [repository path]")
    name = require_workspace(data, validate_name(args[0]))
    repo = current_repository(args[1] if len(args) > 1 else None)
    repos = data["workspaces"][name]["repos"]
    remaining = [existing for existing in repos if not same_path(existing, repo)]
    if len(remaining) == len(repos):
        return "%s is not part of workspace %r" % (repo, name)
    data["workspaces"][name]["repos"] = remaining
    return "removed %s from workspace %r" % (repo, name)


def cmd_delete(data, args):
    if not args:
        raise UsageError("usage: delete <name>")
    name = require_workspace(data, validate_name(args[0]))
    del data["workspaces"][name]
    return "deleted workspace %r" % name


def cmd_rename(data, args):
    if len(args) < 2:
        raise UsageError("usage: rename <old name> <new name>")
    old = require_workspace(data, validate_name(args[0]))
    new = validate_name(args[1])
    if find_workspace(data, new) not in (None, old):
        raise UsageError("workspace %r already exists" % new)
    data["workspaces"][new] = data["workspaces"].pop(old)
    return "renamed workspace %r to %r" % (old, new)


Command = collections.namedtuple("Command", "run description changes_workspaces")

COMMANDS = {
    "generate": Command(cmd_generate, "regenerate the Sublime Merge command, menu and keymap files", False),
    "list": Command(cmd_list, "print all workspaces and their repositories", False),
    "new": Command(cmd_new, "new <name> [path]: create a workspace containing one repository", True),
    "save": Command(cmd_save, "save <name> [path]: create or overwrite a workspace from the open tabs of the window showing the repository", True),
    "add": Command(cmd_add, "add <name> [path]: add a repository to a workspace", True),
    "remove": Command(cmd_remove, "remove <name> [path]: remove a repository from a workspace", True),
    "delete": Command(cmd_delete, "delete <name>: delete a workspace", True),
    "rename": Command(cmd_rename, "rename <old> <new>: rename a workspace", True),
}


def usage():
    lines = ["usage: workspace_manager.py <command> [arguments]", "",
             "[path] defaults to the current directory (the repository Sublime Merge ran the command in).", ""]
    for name, command in COMMANDS.items():
        lines.append("  %-9s %s" % (name, command.description))
    return "\n".join(lines)


def main(argv):
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(usage())
        return 0
    command = COMMANDS.get(argv[0])
    if command is None:
        print("unknown command %r\n\n%s" % (argv[0], usage()), file=sys.stderr)
        return 2
    try:
        data = load_workspaces()
        loaded = copy.deepcopy(data)
        message = command.run(data, argv[1:])
        if data != loaded:
            save_workspaces(data)
            generate(data)
    except UsageError as error:
        print("Workspace Manager: %s" % error, file=sys.stderr)
        return 1
    print(message)
    if command.changes_workspaces:
        notify(data, message.partition("\n")[0])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
